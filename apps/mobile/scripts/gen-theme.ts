/// <reference types="node" />
/**
 * Generates src/theme/tokens.generated.ts from design/design-system/tokens.json (app-shell AC1).
 *
 *   npm run gen:theme
 *
 * The output is committed. A test re-runs renderTheme() and diffs it against the committed file,
 * so a hand-edit or a tokens.json change that wasn't regenerated fails CI.
 *
 * Runs directly on Node 24 (built-in type stripping): keep this file to erasable TypeScript only
 * (no enums, namespaces or parameter properties) and import only `node:` modules.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

type Json = string | number | boolean | null | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

/** Paths relative to apps/mobile. */
export const TOKENS_PATH = '../../design/design-system/tokens.json';
export const OUTPUT_PATH = 'src/theme/tokens.generated.ts';

/** Top-level token groups emitted as-is (each becomes one exported const). */
const GROUPS = ['spacing', 'radii', 'borderWidth', 'shadows', 'zIndex', 'touch', 'layout'] as const;

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function pick(tokens: JsonObject, key: string): JsonObject {
  const value = tokens[key];
  if (!isObject(value)) throw new Error(`tokens.json: "${key}" must be an object`);
  return value;
}

function literal(value: Json, indent: string): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value === 'number' || typeof value === 'boolean' || value === null) return String(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((v) => `${inner}${literal(v, inner)},`).join('\n')}\n${indent}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return '{}';
  const lines = entries.map(([k, v]) => {
    const key = IDENTIFIER.test(k) ? k : `'${k}'`;
    return `${inner}${key}: ${literal(v, inner)},`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function constant(name: string, value: Json, doc: string): string {
  return `/** ${doc} */\nexport const ${name} = ${literal(value, '')} as const;\n`;
}

/** Pure: tokens.json contents in, the generated module's source out. */
export function renderTheme(tokens: JsonObject): string {
  const colors = pick(tokens, 'colors');
  if (!isObject(colors.light) || !isObject(colors.dark)) {
    throw new Error('tokens.json: colors.light and colors.dark are required');
  }
  const typography = pick(tokens, 'typography');
  const fonts = pick(typography, 'fonts');

  const sections = [
    constant('colors', { light: colors.light, dark: colors.dark }, 'Color palettes, light and dark.'),
    constant(
      'fonts',
      { heading: fonts.heading, body: fonts.body, numeric: fonts.numeric },
      'Font families by role. Weights are separate loaded faces (see src/theme).',
    ),
    constant('typeScale', pick(typography, 'scale'), 'Typography scale (px).'),
    ...GROUPS.map((group) => constant(group, pick(tokens, group), `tokens.json → ${group}`)),
  ];

  return [
    '/**',
    ' * @generated by scripts/gen-theme.ts from design/design-system/tokens.json.',
    ' * Do not edit by hand: change tokens.json and run `npm run gen:theme`.',
    ' */',
    '',
    sections.join('\n'),
    'export type ColorScheme = keyof typeof colors;',
    'export type ColorName = keyof (typeof colors)[\'light\'];',
    'export type TypeScaleName = keyof typeof typeScale;',
    '',
  ].join('\n');
}

function main(): void {
  const mobileRoot = resolve(dirname(process.argv[1]), '..');
  const tokens = JSON.parse(readFileSync(resolve(mobileRoot, TOKENS_PATH), 'utf8')) as JsonObject;
  writeFileSync(resolve(mobileRoot, OUTPUT_PATH), renderTheme(tokens));
  console.log(`gen-theme: wrote ${OUTPUT_PATH}`);
}

if (process.argv[1]?.endsWith('gen-theme.ts')) main();
